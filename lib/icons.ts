export function getIcon(name: string): LucideIcon {
  return iconMap[name] ?? Circle;
}

function normaliseBrandName(name: string): string {
  return name
    .toLowerCase()
    .replace(/[.\-+\s]/g, "");
}

export function getBrandIcon(name: string): SimpleIcon | null {
  const key = normaliseBrandName(name);
  return brandIconMap[key] ?? null;
}

